export function mergeMasterCatalog(
  baseCatalog: DeviceSpec[],
  overrides?: CatalogOverrides
): DeviceSpec[] {
  if (!overrides) return baseCatalog;
  const removed = new Set(overrides.removedIds || []);
  const upsertMap = new Map<string, DeviceSpec>();
  for (const item of overrides.upsertedDevices || []) {
    if (item && item.id) {
      upsertMap.set(item.id, item);
    }
  }

  const merged: DeviceSpec[] = [];
  const seen = new Set<string>();

  for (const base of baseCatalog) {
    if (removed.has(base.id)) continue;
    const edited = upsertMap.get(base.id);
    merged.push(edited ?? base);
    seen.add(base.id);
  }

  for (const [id, added] of upsertMap.entries()) {
    if (!seen.has(id) && !removed.has(id)) {
      merged.unshift(added);
    }
  }

  return merged;
}
